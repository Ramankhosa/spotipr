/** Codes that resolve to another profile's rules. */
export const CLAIM_RULE_ALIASES: Record<string, string> = {
  WO: 'PCT',
  WIPO: 'PCT',
  EPO: 'EP',
  GB: 'UK',
  USA: 'US',
}

export function canonicalClaimRuleCode(jurisdiction: string | null | undefined): string {
  const code = String(jurisdiction || '').trim().toUpperCase()
  return CLAIM_RULE_ALIASES[code] || code
}
