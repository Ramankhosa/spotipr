// Built-in claim-rule defaults for the fourteen offices that have drafting
// profiles, plus a neutral profile for anything else.
//
// The runtime resolves rules as: built-in default for the office, then the
// structured fields the DB profile carries (see resolve.ts). The defaults exist
// so claim form never depends on which profile JSON was last imported, and so
// a jurisdiction the DB knows nothing about still gets neutral, defensible
// form rather than US form by accident.
//
// Cells marked "counsel" in the plan (CA and ZA medical forms, BR and ZA CRM
// acceptance, RU treatment methods, AU omnibus) are best current practice and
// are overridable per country in the profile without a deploy.

import { CLAIM_RULES_VERSION, type ClaimRuleProfile } from './types'

type DefaultInput = Omit<ClaimRuleProfile, 'rulesVersion' | 'notes' | 'requireSupportInDescription'> &
  Partial<Pick<ClaimRuleProfile, 'requireSupportInDescription' | 'notes'>>

const EP_EXCLUSIONS = [
  'discovery',
  'mathematical_method',
  'mental_act_business_scheme',
  'computer_program_as_such',
  'presentation_of_information',
  'method_of_treatment',
  'diagnostic_method',
  'plant_animal_variety',
]

function profile(input: DefaultInput): ClaimRuleProfile {
  return {
    rulesVersion: CLAIM_RULES_VERSION,
    requireSupportInDescription: true,
    notes: [],
    ...input,
  }
}

